<h2>Pelvik Konjesyon Sendromu Belirtileri Nelerdir?</h2>
<p>
    Alt karın ve kasık bölgesinde kronik ağrı (6 ay), bazı durumlarda bel ve sırt ağrısı, yorgunluk, halsizlik.
</p>
<p>
    Cinsel işlev sorunları, ağrı (Disparoni), orgazm bozukluğu (Disorgazmi, Anorgazmi, PGAD).
</p>
<p>
    Kalça, bacak, vajina/vulva bölgesinde belirgin varisleşmiş damarlar, hemoroid eşlik edebilir.
</p>
<p>
    İdrar problemleri, idrar yaparken yanma/ağrı (Dizüri), sık idrara çıkma (Pollaküri), ani idrara sıkışma (Urgency), idrar kaçırma (Stres İnkontinans).
</p>
<p>
    Adet dönemlerinde ağrı (Dismenore), karında şişlik, kasık bölgesinde dolgunluk, bel ağrısı gibi şikayetler artabilir.
</p>
<p>
    Adet dönemi bozuklukları, adet görememe (Amenore), uzun süren veya aşırı kanama (Menorji) görülebilir.
</p>

<h2>Pelvik Konjesyon Sendromu Tanısı</h2>
<p>
    Klinik değerlendirme ve görüntüleme yöntemleri, Detaylı Renkli Doppler Ultrasonografi, Manyetik Rezonans (MR) ve Bilgisayarlı tomografi Venografi ile konur.
</p>
<p>
    Tanıda en etkili yöntem (Altın Standart) Tanısal Venografidir (Anjiografi).
</p>

<h2>Pelvik Konjesyon Sendromu Tedavisi</h2>
<p>
    Hastanın etkin şekilde tedavisinin yanında günlük yaşama erken dönüş temel hedeftir.
</p>
<p>
    Cerrahi bir takım yöntemler (Laparoskopik Ven Ligasyonu) kullanabilse de günümüzde ameliyatsız yöntemler (Pelvik Venöz Embolizasyon) en etkili, kalıcı ve hasta konforu yüksek tedavidir.
</p>
<p>
    Pelvik Venöz Embolizasyon ile tedavi sonrası hasta aynı gün ağır efordan uzak normal fiziksel yaşamına geri dönebilir. Hastalık ile ilgili şikayetlerin tam olarak geçmesi, uygun tedavi prosedürlerinin uygulanması ve hastalığın durumuna göre değişmekle birlikte tam olarak çoğunlukla 1 ile 6 ay arasındadır.
</p>
<p>
    Hastaya uygun tedavi ile hastalığın tekrar etme oranı oldukça düşüktür.
</p>

<h2>Doğru Bilinen Yanlışlar</h2>
<ul>
    <li><strong>"Sadece adet döneminde ağrı olur."</strong> Yanlış, ağrı kronik ve sürekli olabilir.</li>
    <li><strong>"Tedavi mutlaka ameliyatla yapılır."</strong> Yanlış, günümüzde ameliyatsız yöntemler daha etkilidir.</li>
    <li><strong>"Tamamen iyileşmez."</strong> Yanlış, uygun tedaviyle şikayetler büyük ölçüde ortadan kalkar.</li>
</ul>
