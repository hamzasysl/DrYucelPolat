<h2>Lipödem Tedavisi</h2>
<p>
    Lipödem tedavisi temel olarak ikiye ayrılır: cerrahi ve cerrahi olmayan yöntemler.
</p>
<p>
    Cerrahi tedavilerde en sık kullanılan özel liposuction yöntemlerinde anormal yağ doku hacminde azalma yani incelme sağlansa da şekil bozukluğu geçmeyebilir.
</p>
<p>
    Cerrahi olmayan yöntemlerde transkütan lazer / radyofrekans, transdermal radyofrekans, kompresyon çorabı, medikal tedavi, yaşam biçimi değişiklikleri, manuel lenfatik masaj kullanılır. Bu tedaviler destek tedavileri olup hastaya özgü bir yaklaşımla kombinasyonu belirlenir. Bu tedaviye Kompleks dekonjestif terapi denir ve başarılı bir sonuç için hastaya özgün tedavi seçilir.
</p>

<h2>Lipödem Zamanla İlerler mi / Tedavi Sonrası Tekrarlar mı?</h2>
<p>
    Lipödem zamanla ilerleyen kronik bir hastalıktır. Tedavi sonrası tekrarlama riskini azaltmak için doktorunuza danışınız.
</p>

<h2>Kompresyon Giysisi Ne Kadar Süre Kullanılır?</h2>
<p>
    Kompresyon giysisi destekleyici bir tedavi olup, tedavide kullanımına ve süresine hekiminiz karar vermelidir.
</p>

