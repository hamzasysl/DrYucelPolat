<p>
    Kanıtlanmış DVT atağı geçiren hastaların yaklaşık üçte birinde çeşitli derecelerde Posttrombotik Sendrom (bacak toplardamarındaki kapakçıkların kalıcı hasar görmesi) şikayetleri (ağrı, ödem, ağırlık hissi, egzersiz intoleransı, hiperpigmentasyon, kaşıntı, ülser) gözükür.
</p>
<p>
    DVT hem genetik hem kazanılmış birçok faktöre bağlı gelişir. Varis doğrudan veya dolaylı olarak DVT riskini 4 veya 5 kat artırabilir. Detaylı klinik değerlendirme için hekiminize başvurun.
</p>
<p>
    Yüzeysel toplardamarların, damar duvarının inflamasyonu ve pıhtı ile tıkanmasına Tromboflebit denir. Bacakta gelişen tromboflebitin en sık nedeni tedavi edilmemiş ileri seviye varislerdir.
</p>
<p>
    Tromboflebitin en sık nedeni hastane ortamında kola uygulanan damar yolları (IV kateter, serum iğneleri) ve tıbbi enfeksiyonlardır.
</p>

<h2>Derin Ven Trombozu Belirtileri Nelerdir?</h2>
<p>
    En sık görülen belirtiler, bacakta aniden gelişen şişlik, gerginlik, ağrı, kramp, renk değişikliği, kızarıklık, ısı artışı, sıcaklık, ciltte sertleşme, dolgunluk hissi olabilir.
</p>
<p>
    Pıhtının yerinden kopup Akciğere gitmesi Pulmoner Emboli adını alır ve acil bir durumdur. Ani başlayan açıklanamayan nefes darlığı, göğüs ağrısı, yan ağrı, öksürük, çarpıntı (Taşikardi), hızlı nefes alıp verme (Takipne), tansiyon düşüklüğü, baş dönmesi, bayılma (senkop) gibi şikayetler görülebilir.
</p>
<p>
    Uygun ve yeterli tedavi edilmeyen DVT atağı uzun dönemde Posttrombotik Sendroma yol açabilir (Venöz Ülser, iyileşmesi güç yara).
</p>
<p>
    Derin ven trombozunda bacaklardaki ana toplardamarların pıhtı ile aniden ve tam olarak tıkanması durumunda çok ağır ve hayati bir tablo ortaya çıkar. Bu duruma Flegmasia Alba ve Cerulea Dolens adı verilir. Acil müdahale gereklidir.
</p>

<h2>Derin Ven Trombozu Tanısı Nasıl Konur?</h2>
<p>
    Derin ven trombozunda, sıklıkla gelişen klinik semptom ve bulgular hastaların %30 ile %80'inde saptanabildiği için sadece klinik belirtilere dayanarak tanı koymak güvenilir bir yöntem değildir.
</p>
<p>
    Detaylı Renkli Doppler Ultrasonografi tanıda altın standarttır.
</p>
<p>
    D-dimer özellikle venöz tromboembolinin dışlanmasında ve tekrar riskinin değerlendirilmesinde sık kullanılan bir laboratuvar testidir.
</p>
<p>
    Akciğer Embolisi şüphesinde BT Pulmoner Anjiyografi akciğer damarlarındaki pıhtıyı gösteren tetkiktir.
</p>

<h2>Derin Ven Trombozu Tedavisi Nedir?</h2>
<p>
    Derin Ven Trombozu tedavi planı Kalp ve Damar cerrahisi uzmanı tarafından yapılmalıdır. Tedavi hemen başlatılması gereken acil ve tıbbi bir süreçtir.
</p>
<p>
    Tedavinin amacı, tekrarlamasını önlemek, Posttrombotik sendroma gidişatı önlemek ve Pulmoner Emboliye bağlı gelişebilecek ölümü engellemektir.
</p>
<p>
    Tedavinin temel bileşeni medikal olup geleneksel olarak heparini takiben Antikoagülan (kan sulandırıcı) ilaçlardır.
</p>
<p>
    Kateter ile trombolitik tedavi, ultrason ile hızlandırılmış kateter yollu trombolitik tedavi (EKOS), farmako-mekanik reolitik trombektomi (Anjiojet) gibi girişimsel yöntemler hastanın durumuna göre kullanılabilir. Özellikle hastalığın ilk 14 gününde başarı şansı daha yüksektir.
</p>
<p>
    Kronik derin ven trombozunda venöz stentleme kullanımı hastaya göre değerlendirilir.
</p>
<p>
    Kompresyon tedavi süresi doktorunuz tarafından belirlenir. Tedavi sırasında yürümek veya normal fiziksel yaşama dönüş doktorunuzun kontrolünde olmalıdır.
</p>
<p>
    DVT tekrarlayabilen bir hastalıktır. Tedavisini tamamlayan hastalarda sonraki 10 yılda yaklaşık %30 oranında hastalık tekrarlayabilir. Tedavi süreci ve sonrası doktor kontrolü önemlidir.
</p>

<h2>DVT Hakkında Doğru Bilinen Yanlışlar</h2>
<ul>
    <li><strong>"Varis sadece estetik bir sorundur."</strong> Yanlış. Varis, DVT riskini 4-5 kat artırabilir ve ciddi sağlık sorunlarına yol açabilir.</li>
    <li><strong>"DVT sadece yaşlılarda görülür."</strong> Yanlış. Gençlerde de DVT gelişebilir; risk faktörleri genetik veya kazanılmış olabilir.</li>
    <li><strong>"DVT tedavi edilmezse sadece bacakta kalır."</strong> Yanlış. Pıhtı koparak akciğere gidebilir ve hayatı tehdit eden Pulmoner Emboliye yol açabilir.</li>
    <li><strong>"Klinik belirtiler tek başına tanı koymak için yeterlidir."</strong> Yanlış. Tanıda altın standart Renkli Doppler Ultrasonografidir; sadece belirtilere dayanmak güvenilir değildir.</li>
    <li><strong>"Tedavi tamamlandıktan sonra DVT bir daha tekrarlamaz."</strong> Yanlış. DVT tekrarlayabilen bir hastalıktır; tedavi sonrası 10 yıl içinde yaklaşık %30 oranında yeniden görülebilir.</li>
</ul>
