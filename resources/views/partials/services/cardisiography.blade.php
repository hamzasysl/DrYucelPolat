<h2>CSG Testi Ne Ölçer?</h2>
<p>
    CSG testi ile kısa bir zamanda kalbin ritm problemleri, iskemi (kanlanma bozukluğu), yapısal anomaliler, kalp krizi riski gibi durumlar hakkında bilgi sahibi olunması mümkündür.
</p>
<p>
    CSG testi sonuçları değerlendirilmesi önemli olup doktor kontrolünde olması gereklidir.
</p>
