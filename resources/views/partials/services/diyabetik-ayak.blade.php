<h2>Diyabetik Ayak Belirtileri Nelerdir?</h2>
<p>
    Nöropati yani sinir hasarına bağlı ayaklarda his kaybı meydana gelebilir. Hasta yara ve yanıkları hissetmez. Genellikle hastalığın ilk belirtisi nöropatiye bağlıdır.
</p>
<p>
    Dolaşım bozukluğuna bağlı olarak ayakta ısı ve renk değişimi (morarma) olabilir. Dolaşımı bozulan uzuvda oluşan yarada akıntı, koku oluşabilir, enfeksiyon gelişebilir. Bu yaraların iyileşmesi için mikrovasküler dolaşımın sağlıklı olması gereklidir.
</p>
<p>
    Süreç doku ve uzuv kaybına gidebilir.
</p>

<h2>Tanı</h2>
<p>
    Fiziksel muayene ile dolaşım kontrolü için detaylı doppler ultrasonografi, Ayak bileği–Kol indeksi (ABI), BT/MR anjio gibi tetkikler ve görüntülemeler kullanılır.
</p>

<h2>Diyabetik Ayak Tedavisi</h2>
<p>
    Tedavide bozulmuş olan dolaşımın düzeltilmesi amacıyla birçok modern girişimsel yöntem (İntravasküler Litotripsi, PTA, Aterektomi) ile cerrahi yöntemler (Bacak damarı bypassı, Distal bypass) kullanılmakta olup önemli olan mikrovasküler damar yatağının kanlanmasıdır (Revaskülarizasyon).
</p>
<p>
    İyileşmesi güç, kronik yaralarda (Diyabetik ayak ülseri, venöz ülser, basıya bağlı yaralar) hastaya özgü multidisipliner aşamalı bir yaklaşım tedavide temel hedeftir. Yarada tam iyileşme sağlanabilir. Yaraya yaklaşım hastaya özgü olup detaylar için hekiminize danışınız.
</p>

<h2>Diyabetik Ayak Hakkında Doğru Bilinen Yanlışlar</h2>
<ul>
    <li><strong>"Ayak yaraları kendiliğinden geçer."</strong> Yanlış, mutlaka tıbbi müdahale gerekir.</li>
    <li><strong>"Ayaklarda his kaybı önemsizdir."</strong> Yanlış, diyabetik ayak için en önemli erken belirtidir.</li>
    <li><strong>"Tedavi edilse bile iyileşmez."</strong> Yanlış, doğru yöntemlerle tam iyileşme mümkündür.</li>
</ul>
