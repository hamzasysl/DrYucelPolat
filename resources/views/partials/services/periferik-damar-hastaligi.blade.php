<h2>Damar Tıkanıklığı Belirtileri</h2>
<p>
    Periferik arter hastalığı başlangıcında hiç belirti vermeyebilir. Damar tıkanıklık seviyesi arttıkça belirtiler değişir.
</p>
<p>
    En tipik belirti aralıklı topallamadır (Kladikasyo). Hasta yürürken veya merdiven çıkarken bacakta ağrı, kramp, yorgunluk gelişmesi üzerine hasta dinlenir, sonrasında efora devam edince şikayetler tekrarlar.
</p>
<p>
    Damardaki darlık ilerleyince hastada sadece hareket halinde değil dinlenme esnasında da ağrı olur (İstirahat ağrısı). Zamanla etkilenen bölgede cilt parlak ince bir hal alır, tüyler dökülebilir, tırnak değişikliği (kalınlaşma, uzama hızında yavaşlama) meydana gelebilir.
</p>
<p>
    Cinsel fonksiyon bozukluğu meydana gelebilir.
</p>
<p>
    Ayaklarda soğukluk ve renk değişikliği olabilir. Periferik nabızlar kaybolabilir (ayak bileği ve ayak üzerinden).
</p>
<p>
    İleri evrelerde iyileşmesi güç yaralar ve ülserler olabilir. Doku ölümü ve kangren gibi hayatı tehdit eden durumlar olabilir.
</p>
<p>
    Ağrı, solukluk, soğukluk, uyuşma, hissizlik gibi belirtilerin aniden oluşması durumuna ani gelişen emboli (Akut arteriyel emboli / Akut ekstremite iskemisi) denir ve saatlerle yarışan acil müdahale gereklidir.
</p>

<h2>Damar Tıkanıklığı Tanısı Nasıl Konur?</h2>
<p>
    Detaylı bir klinik değerlendirme ve fizik muayenenin yanında bacak darlıklarında Ankle-Brachial (ayak bileği–kol indeksi) testi kullanılabilir.
</p>
<p>
    Girişimsel olmayan öne çıkan tetkik olarak doppler ultrasonografi kullanılabilir.
</p>
<p>
    Doppler ultrasonografi Aortailiyak (Leriche sendromu) segment hastalığını göstermede yetersiz olabilir. Bu durumda Bilgisayarlı tomografi anjiyografi (BTA), Manyetik rezonans anjiografi (MRA), Konvansiyonel arteriyografi ve Dijital substraksiyon anjiografisi kullanılabilir.
</p>

<h2>Damar Tıkanıklığı Tedavisi</h2>
<p>
    Periferik arter hastalığı tedavisinde tedavi planı hastaya özgüdür. Şikayetlerin derecesi, tıkanıklığın yeri ve seviyesine göre tedavi planlanır. Ani gelişen tıkanıklıklar acil müdahale gerektirir.
</p>

<h3>Yaşam Biçimi Değişiklikleri</h3>
<p>
    Sigaranın kesin olarak bırakılması, beslenme değişikliği, egzersiz, ayak bakımı gibi.
</p>

<h3>İlaç Tedavisi</h3>
<p>
    Kan sulandırıcı ilaçlar (aspirin vb.), Semptomatik ilaçlar (Silostazol vb.), Kolesterol, tansiyon ve diyabet (Şeker) hastalığının medikal tedavisi.
</p>

<h3>Ameliyatsız Girişimsel Yöntemler</h3>
<p>
    Aort bifurkasyonunun kaplı endovasküler rekonstrüksiyonu (CERAB), İlaç kaplı balon anjıoplasti (Perkütan translüminal Angioplasti – PTA), Stent yerleştirme (Perkütan translüminal stentleme – PTS), Arterektomi (Rotasyonel – Jetstream kateteri, Lazer – Turbo Elite kateteri gibi), Intravasküler litotripsi (Shockwave), Nokta stentleme (Spot).
</p>

<h3>Cerrahi Tedaviler</h3>
<p>
    Bypass (Köprüleme) ameliyatı, Endarterektomi, Hibrit cerrahi (kapalı yöntemler ile açık ameliyatın aynı anda uygulanması).
</p>

<p>
    6 ila 12 ayda yeniden tıkanma oranı %10 ile %60 arasında değişir. Bu değişken oran birçok faktöre bağlıdır (kullanılan yöntem, risk faktörleri). Hastanın düzenli takibi önemlidir.
</p>

<h2>Periferik Damar Hastalığı İle İlgili Doğru Bilinen Yanlışlar</h2>
<ul>
    <li><strong>"Damar tıkanıklığı sadece kalpte olur."</strong> Yanlış, bacak ve kollarda da görülebilir.</li>
    <li><strong>"Sadece yaşlılarda damar tıkanıklığı olur."</strong> Yanlış, gençlerde de gelişebilir.</li>
    <li><strong>"Belirti yoksa damarlar sağlıklıdır."</strong> Yanlış, hastalık başlangıçta belirti vermeyebilir.</li>
    <li><strong>"Tedavi sonrası damar bir daha tıkanmaz."</strong> Yanlış, 6-12 ay içinde yeniden tıkanma oranı %10-60 arasında değişebilir. Takip önemlidir.</li>
</ul>
